#!/usr/bin/env python3
"""Compile the editable garden SVG contours into native CoreGraphics paths.

No SVG parser or bitmap assets are required at runtime. Re-run after editing the
masters in design/icon/seasonal-garden/paths. Menu-bar masters omit leaf veins and
very small detached pieces; the 52pt masters retain the approved full silhouette.
"""
from pathlib import Path
import hashlib
import re
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
FLOWERS = ["plum", "magnolia", "crabapple", "gardenia", "lotus", "osmanthus", "chrysanthemum", "camellia"]
NUMBER = r"[-+]?(?:\d*\.\d+|\d+\.?\d*)(?:[eE][-+]?\d+)?"

def multiply(a, b):
    aa, ab, ac, ad, ax, ay = a
    ba, bb, bc, bd, bx, by = b
    return (aa*ba+ac*bb, ab*ba+ad*bb, aa*bc+ac*bd, ab*bc+ad*bd,
            aa*bx+ac*by+ax, ab*bx+ad*by+ay)

def transform(value):
    result = (1, 0, 0, 1, 0, 0)
    for name, args in re.findall(r"([a-zA-Z]+)\(([^)]*)\)", value):
        p = [float(x) for x in re.findall(NUMBER, args)]
        if name == "translate": t = (1, 0, 0, 1, p[0], p[1] if len(p)>1 else 0)
        elif name == "scale": t = (p[0], 0, 0, p[1] if len(p)>1 else p[0], 0, 0)
        elif name == "matrix": t = tuple(p)
        else: raise ValueError(f"Unsupported SVG transform: {name}")
        result = multiply(result, t)
    return result

def point(x, y, matrix):
    a,b,c,d,tx,ty = matrix
    return f"CGPoint(x: {a*x+c*y+tx:.4f}, y: {b*x+d*y+ty:.4f})"

def commands(data, matrix):
    tokens = re.findall(r"[a-zA-Z]|"+NUMBER, data)
    i=0
    result=[]
    command=None
    arities={"M":2,"L":2,"C":6,"Q":4}
    while i<len(tokens):
        if tokens[i].isalpha():
            command=tokens[i]; i+=1
            if command in ("Z","z"):
                result.append("p.closeSubpath()")
                command=None
                continue
        if command not in arities:
            raise ValueError(f"Unsupported SVG path command: {command}")
        n=arities[command]
        args=[float(v) for v in tokens[i:i+n]]; i+=n
        pts=[point(args[j],args[j+1],matrix) for j in range(0,n,2)]
        if command=="M": result.append(f"p.move(to: {pts[0]})"); command="L"
        elif command=="L": result.append(f"p.addLine(to: {pts[0]})")
        elif command=="C": result.append(f"p.addCurve(to: {pts[2]}, control1: {pts[0]}, control2: {pts[1]})")
        elif command=="Q": result.append(f"p.addQuadCurve(to: {pts[1]}, control: {pts[0]})")
    return result

def paths(element, parent=(1,0,0,1,0,0)):
    matrix=multiply(parent,transform(element.attrib.get("transform","")))
    if element.tag.rsplit("}",1)[-1]=="path":
        return [commands(element.attrib["d"],matrix)]
    result=[]
    for child in element: result.extend(paths(child,matrix))
    return result

def swift_array(name, outlines):
    rows=[f"    private static let {name} = ImmutablePaths(values: ["]
    for outline in outlines:
        rows.append("        {")
        rows.append("            let p = CGMutablePath()")
        rows.extend("            "+line for line in outline)
        rows.append("            return p.copy()!")
        rows.append("        }(),")
    rows.append("    ])")
    return "\n".join(rows)

entries=[]
arrays=[]
for flower in FLOWERS:
    full=ROOT/"design/icon/seasonal-garden/paths"/f"{flower}.svg"
    menu=full.with_name(f"{flower}-menu.svg")
    if not full.exists() or not menu.exists():
        raise FileNotFoundError(f"Both full and menu SVG masters are required: {flower}")
    for label, source in [("Full",full),("Menu",menu)]:
        data=source.read_bytes()
        tree=ET.fromstring(data)
        if any(e.tag.rsplit("}",1)[-1]=="image" for e in tree.iter()):
            raise ValueError(f"Bitmap found in {source}")
        outlines=paths(tree)
        if not outlines: raise ValueError(f"Empty artwork in {source}")
        entries.append(f"// {source.relative_to(ROOT)} sha256:{hashlib.sha256(data).hexdigest()}")
        arrays.append(swift_array(flower+label,outlines))

body="""// Generated by scripts/compile-garden-artwork.py. Edit the SVG masters, then regenerate.
import CoreGraphics
import YiyuCore

enum GardenSilhouetteArtwork {
    // Every stored path is an immutable CGPath copy. The mutable builders are local
    // and never escape, so these CF objects can be shared by drawing contexts.
    private struct ImmutablePaths: @unchecked Sendable {
        let values: [CGPath]
    }

    /// Paths use the editable SVG masters' 128 × 128 coordinate system.
    static func paths(for flower: GardenFlower, compact: Bool) -> [CGPath] {
        switch flower {
"""
for flower in FLOWERS:
    body+=f"        case .{flower}: (compact ? {flower}Menu : {flower}Full).values\n"
body+="        }\n    }\n\n"+"\n\n".join(arrays)+"\n}\n"
target=ROOT/"Sources/Yiyu/Views/GardenSilhouetteArtwork.swift"
target.write_text("\n".join(entries)+"\n"+body)
print(f"Compiled {len(FLOWERS)} full and menu masters into {target.relative_to(ROOT)}")
